#!/usr/bin/env python3
"""Lint a Git commit message for Conventional Commits + iuricode/padroes-de-commits rules.
Usage:
  python3 check_commit_msg.py [--require-emoji] MSGFILE
  python3 check_commit_msg.py [--require-emoji] -   # read stdin
Exit: 0 if no HIGH findings, 1 if HIGH, 2 usage/IO error.
MEDIUM and LOW do not fail the process. Exit 0 is not a clean bill of health.
Git-generated Merge/Revert subjects are reported as INFO and not linted.
"""
from __future__ import annotations

import re
import sys

TYPES = (
    "feat", "fix", "docs", "test", "build", "perf", "style",
    "refactor", "chore", "ci", "raw", "cleanup", "remove",
    "init", "revert", "security",
)
CONV = re.compile(
    rf"^(?P<type>{'|'.join(TYPES)})"
    r"(?:\((?P<scope>[^)]*)\))?(?P<break>!)?:(?P<space>\s*)(?P<sub>.*)$"
)
# Same shape, any case / unknown word as type. Description may be empty.
LOOSE = re.compile(
    r"^(?P<type>[A-Za-z]+)"
    r"(?:\((?P<scope>[^)]*)\))?"
    r"(?P<break>!)?"
    r":(?P<space>\s*)(?P<sub>.*)$"
)
SHORTCODE_EMOJI = re.compile(r"^(?P<emoji>:[a-z0-9_+-]+:)(?P<space>\s*)(?P<rest>.*)$")
UNICODE_EMOJI = re.compile(
    r"^(?P<emoji>"
    r"[\U0001F000-\U0001FAFF\u2190-\u21FF\u2300-\u23FF\u2600-\u27BF\u2B00-\u2BFF]"
    r"(?:[\ufe0e\ufe0f\u20e3\U0001F3FB-\U0001F3FF]"
    r"|\u200d[\U0001F000-\U0001FAFF\u2190-\u21FF\u2300-\u23FF\u2600-\u27BF\u2B00-\u2BFF\ufe0e\ufe0f\u20e3\U0001F3FB-\U0001F3FF])*"
    r")(?P<space>\s*)(?P<rest>.*)$"
)
# Subjects generated by git itself; not the author's prose
GIT_GENERATED = re.compile(
    r"^(Merge (branch|pull request|remote-tracking branch|tag) "
    r"|Merge [0-9a-f]{7,} into |Revert \")"
)
AUTOSQUASH = re.compile(r"^(fixup|squash|amend)! ")
# Description is only an issue pointer: "#123", "Fixes #123", "Resolves #12".
ISSUE_ONLY = re.compile(
    r"(?:(?:fix(?:es)?|close[sd]?|resolve[sd]?)\s+)?#\d+"
    r"|fix(?:es)?\s+\d+",
    re.IGNORECASE,
)
# "changes to the parser" is a noun phrase; "changes the parser" is third person.
THIRD_PERSON = re.compile(
    r"^(?:fixes|adds|updates|removes)\b|^changes(?!\s+to\b)\b",
    re.IGNORECASE,
)
SCISSOR = "# ------------------------ >8 ------------------------"


def _strip_leading_emoji(subject: str) -> tuple[str | None, str, bool]:
    """Return (emoji, rest_of_subject, had_space_after_emoji)."""
    for pattern in (SHORTCODE_EMOJI, UNICODE_EMOJI):
        match = pattern.match(subject)
        if match:
            return match.group("emoji"), match.group("rest").lstrip(), bool(match.group("space"))
    return None, subject, True


def _visible_lines(text: str) -> list[tuple[int, str]]:
    """Return (1-based original line number, text) minus comments and the scissor."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if text.startswith("\ufeff"):
        text = text[1:]
    entries: list[tuple[int, str]] = []
    for lineno, ln in enumerate(text.split("\n"), start=1):
        if ln.strip() == SCISSOR:
            break
        if ln.startswith("#"):
            continue
        entries.append((lineno, ln))
    while entries and not entries[-1][1].strip():
        entries.pop()
    while entries and not entries[0][1].strip():
        entries.pop(0)
    return entries


def lint(text: str, *, require_emoji: bool = False) -> list[tuple[str, str, str]]:
    entries = _visible_lines(text)
    findings: list[tuple[str, str, str]] = []
    if not entries or not entries[0][1].strip():
        findings.append(("HIGH", "empty", "Message is empty"))
        return findings
    subject = entries[0][1].strip()
    body_entries = entries[1:]
    body_lines = [ln for _, ln in body_entries]
    if GIT_GENERATED.match(subject):
        findings.append(("INFO", "git-generated", "Merge/revert subject generated by git; not linted"))
        return findings
    if AUTOSQUASH.match(subject):
        findings.append((
            "MEDIUM", "autosquash-pending",
            "fixup!/squash! commit: run `git rebase -i --autosquash` before merging",
        ))
        return findings
    emoji, core_subject, has_emoji_space = _strip_leading_emoji(subject)
    if emoji and core_subject and not has_emoji_space:
        findings.append((
            "MEDIUM", "emoji-space",
            "Insert a space between the leading emoji and type (`✨ feat: ...`)",
        ))
    if require_emoji and emoji is None:
        findings.append((
            "LOW", "emoji-missing",
            "Consider adding a leading emoji (e.g. `✨` or `:sparkles:`) per iuricode/padroes-de-commits",
        ))
    m = CONV.match(core_subject)
    if not m:
        loose = LOOSE.match(core_subject)
        if loose and loose.group("type").lower() in TYPES:
            findings.append((
                "HIGH", "type-case",
                f"Use lowercase type `{loose.group('type').lower()}:`",
            ))
            sub = loose.group("sub").strip()
        elif loose:
            findings.append((
                "HIGH", "type-unknown",
                f"Unknown type `{loose.group('type')}`; use one of: {', '.join(TYPES)}",
            ))
            sub = loose.group("sub").strip()
        else:
            findings.append((
                "HIGH", "type-missing",
                "Subject should start with [emoji] type[optional scope][!]: description",
            ))
            sub = core_subject
    else:
        sub = m.group("sub").strip()
        if m.group("scope") is not None and not m.group("scope").strip():
            findings.append(("MEDIUM", "empty-scope", "Scope parentheses are empty"))
        if sub and m.group("space") != " ":
            findings.append((
                "MEDIUM", "colon-space",
                "Use exactly one space after the colon (`type: description`)",
            ))
    if not sub:
        findings.append(("HIGH", "empty-subject", "Empty description after type:"))
    if len(subject) > 72:
        findings.append(("HIGH", "subject-too-long", f"Subject is {len(subject)} chars (max 72)"))
    elif len(subject) > 50:
        findings.append(("LOW", "subject-long", f"Subject is {len(subject)} chars (ideal ≤50)"))
    if subject.endswith("."):
        findings.append(("MEDIUM", "subject-period", "Omit trailing period on subject"))
    if re.match(r"^(fixed|added|updated|removed|changed|deleted)\b", sub, re.I):
        findings.append(("MEDIUM", "past-tense", "Use imperative mood (fix/add/update), not past tense"))
    if THIRD_PERSON.match(sub):
        findings.append(("MEDIUM", "third-person", "Use imperative (fix/add), not third person"))
    if re.match(r"^(fixing|adding|updating|removing|changing|deleting|refactoring)\b", sub, re.I):
        findings.append(("MEDIUM", "gerund", "Use imperative (fix/add), not -ing form"))
    # Uppercase only: "todo list" is a real subject; WIP/TODO/TMP are temporary markers.
    if re.search(r"\b(WIP|TODO|TMP)\b", subject):
        findings.append(("HIGH", "wip", "Subject looks temporary (WIP/TODO/TMP)"))
    if sub and ISSUE_ONLY.fullmatch(sub):
        findings.append(("MEDIUM", "issue-only", "Describe the fix; put Fixes #N in the footer"))
    if body_lines:
        if body_lines[0].strip() != "":
            findings.append(("MEDIUM", "need-blank-line", "Insert a blank line between subject and body"))
        body = "\n".join(body_lines).strip()
        if body:
            for lineno, bl in body_entries:
                if len(bl) > 100 and not bl.startswith("http"):
                    findings.append((
                        "LOW", "body-wrap",
                        f"Line {lineno} is {len(bl)} chars; wrap near 72 when possible",
                    ))
                    break
            if re.search(r"^(updated? files?|changes made):?\s*$", body, re.I | re.M):
                findings.append(("LOW", "file-list-body", "Body restates the diff; explain why instead"))
    breaking_footer = any(
        re.match(r"^BREAKING[ -]CHANGE:", ln) for ln in body_lines
    )
    if m and m.group("break") and not breaking_footer:
        findings.append((
            "LOW", "breaking-explain",
            "Marked breaking (!) — consider a BREAKING CHANGE: footer explaining impact",
        ))
    return findings


def main(argv: list[str]) -> int:
    require_emoji = False
    positional: list[str] = []
    for arg in argv:
        if arg == "--require-emoji":
            require_emoji = True
        elif arg.startswith("-") and arg != "-":
            print(__doc__, file=sys.stderr)
            return 2
        else:
            positional.append(arg)
    if len(positional) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    target = positional[0]
    try:
        if target == "-":
            text = sys.stdin.read()
        else:
            with open(target, encoding="utf-8", errors="replace") as fh:
                text = fh.read()
    except OSError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    findings = lint(text, require_emoji=require_emoji)
    for sev, rid, msg in findings:
        print(f"[{sev}] {rid}: {msg}")
    counts = {s: sum(1 for f in findings if f[0] == s) for s in ("HIGH", "MEDIUM", "LOW", "INFO")}
    print(
        f"\n{counts['HIGH']} HIGH, {counts['MEDIUM']} MEDIUM, {counts['LOW']} LOW"
        + (f", {counts['INFO']} INFO" if counts["INFO"] else "")
    )
    print("Heuristic only: exit 0 means no HIGH. MEDIUM still needs an edit. Confirm with the references.")
    return 1 if counts["HIGH"] else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
