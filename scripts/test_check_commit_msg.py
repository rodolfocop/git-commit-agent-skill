#!/usr/bin/env python3
"""Stdlib tests for check_commit_msg.lint. Run: python3 scripts/test_check_commit_msg.py"""
from __future__ import annotations

import importlib.util
import unittest
from pathlib import Path


def _load():
    path = Path(__file__).with_name("check_commit_msg.py")
    spec = importlib.util.spec_from_file_location("check_commit_msg", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


mod = _load()
lint = mod.lint


def ids(text: str, *, require_emoji: bool = False) -> set[str]:
    return {rid for _, rid, _ in lint(text, require_emoji=require_emoji)}


class LintTests(unittest.TestCase):
    def test_good_conventional_message(self):
        text = (
            "feat(api): add per-token rate limiting\n"
            "\n"
            "Prevent partner storms from exhausting the primary DB pool.\n"
        )
        self.assertEqual(lint(text), [])

    def test_good_unicode_and_shortcode_emoji_messages(self):
        samples = [
            "✨ feat(auth): add login page\n",
            ":sparkles: feat(auth): add login page\n",
            "♻️ refactor(parser): simplify token validation\n",
            "🔒️ security(api): enforce JWT signature check\n",
            "🗑️ remove: delete deprecated v1 billing module\n",
            "🧹 cleanup: remove unused helper functions\n",
            "🗃️ raw: add 2026 tax bracket parameters\n",
            "🎉 init: initial repository setup\n",
        ]
        for sample in samples:
            with self.subTest(sample=sample):
                self.assertEqual(lint(sample), [])

    def test_missing_space_after_emoji(self):
        self.assertIn("emoji-space", ids("✨feat(auth): add login\n"))
        self.assertIn("emoji-space", ids(":sparkles:feat(auth): add login\n"))

    def test_require_emoji_flag(self):
        self.assertNotIn("emoji-missing", ids("feat: add login\n", require_emoji=False))
        self.assertIn("emoji-missing", ids("feat: add login\n", require_emoji=True))
        self.assertNotIn("emoji-missing", ids("✨ feat: add login\n", require_emoji=True))

    def test_non_ascii_word_is_not_treated_as_emoji(self):
        self.assertIn("type-missing", ids("ação: ajustar layout\n"))

    def test_uppercase_type_after_emoji(self):
        self.assertIn("type-case", ids("✨ Feat: add login\n"))

    def test_issue_only_after_type(self):
        self.assertIn("issue-only", ids("fix: #123\n"))
        self.assertIn("issue-only", ids("🐛 fix: Resolves #123\n"))

    def test_todo_word_is_not_a_temporary_marker(self):
        self.assertNotIn("wip", ids("feat(ui): add todo list for reviewers\n"))

    def test_uppercase_wip_is_high(self):
        found = lint("feat: WIP parser\n")
        self.assertIn(("HIGH", "wip", "Subject looks temporary (WIP/TODO/TMP)"), found)

    def test_capitalized_type_without_description(self):
        found = {rid for _, rid, _ in lint("Feat:\n")}
        self.assertIn("type-case", found)
        self.assertIn("empty-subject", found)
        self.assertNotIn("type-missing", found)

    def test_changes_to_is_a_noun(self):
        self.assertNotIn(
            "third-person",
            ids("refactor(parser): changes to token handling\n"),
        )

    def test_changes_the_is_third_person(self):
        self.assertIn("third-person", ids("refactor(parser): changes the parser\n"))

    def test_body_line_number_keeps_original_position(self):
        long = "x" * 115
        text = f"feat: add parser\n\n# comment\n{long}\n"
        wrap = [msg for sev, rid, msg in lint(text) if rid == "body-wrap"]
        self.assertEqual(wrap, ["Line 4 is 115 chars; wrap near 72 when possible"])

    def test_merge_is_info_only(self):
        found = lint("Merge branch 'feature/x' into main\n")
        self.assertEqual(
            found,
            [("INFO", "git-generated", "Merge/revert subject generated by git; not linted")],
        )

    def test_subject_length_boundaries(self):
        at_50 = "feat: " + "a" * 44  # 6 + 44 = 50
        at_72 = "feat: " + "a" * 66
        at_73 = "feat: " + "a" * 67
        self.assertNotIn("subject-long", ids(at_50 + "\n"))
        self.assertIn("subject-long", ids(at_72 + "\n"))
        self.assertNotIn("subject-too-long", ids(at_72 + "\n"))
        self.assertIn("subject-too-long", ids(at_73 + "\n"))


if __name__ == "__main__":
    unittest.main()
